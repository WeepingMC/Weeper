package com.github.weepingmc.packet.options;

/**
 * Represents the status of an entity.
 */
public enum EntityStatus {
    /**
     * Entity is on fire.
     */
    IS_ON_FIRE,
    /**
     * Entity is crouching.
     */
    IS_CROUCHING,
    /**
     * Entity is sprinting.
     */
    IS_SPRINTING,
    /**
     * Entity is swimming.
     */
    IS_SWIMMING,
    /**
     * Entity is invisible.
     */
    IS_INVISIBLE,
    /**
     * Entity has a glowing effect.
     */
    HAS_GLOWING_EFFECT,
    /**
     * Entity is flying with elytra.
     */
    IS_FLYING_WITH_ELYTRA
}
